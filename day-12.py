'''
1. Inside the editor, complete the following steps:
2. Create a variable i with the value 0
3. Write a while loop that runs as long as i is less than 6
4. Inside the loop: increment i by 1
5. If i equals 3, use continue to skip that iteration
6. Print i
'''
 # create a variable i with the value 0
i = 0

 # Create a while loop taht runs as long as i is less than 6
while i < 6:
    i += 1
    if i == 3:
        continue
    print(i)
